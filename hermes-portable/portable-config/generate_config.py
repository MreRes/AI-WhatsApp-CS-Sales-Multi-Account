#!/usr/bin/env python3
"""
Configuration generator for hermes-portable.

Renders config.yaml and .env templates with user input or defaults.
Supports both Auto (demo) and Interactive (with prompts) modes.
"""

import argparse
import os
import sys
from pathlib import Path
from typing import Dict, Optional
import json


class ConfigGenerator:
    """Generate hermes portable configuration files."""

    def __init__(self, mode: str = "auto", output_dir: Optional[Path] = None):
        self.mode = mode.lower()
        self.output_dir = output_dir or Path.cwd() / "data"
        self.config_data: Dict[str, any] = {}

    def generate_env(
        self,
        api_key: Optional[str] = None,
        telegram_token: Optional[str] = None,
        telegram_chat_id: Optional[str] = None,
    ) -> str:
        """Generate .env content."""
        if not api_key:
            if self.mode == "auto":
                api_key = "sk-or-test-demo-key-no-api-configured"
            else:
                api_key = input(
                    "Enter LLM API key (OpenRouter/Anthropic/Google) or press Enter for demo: "
                ).strip() or "sk-or-test-demo-key-no-api-configured"

        if not telegram_token and self.mode == "interactive":
            telegram_token = input(
                "Enter Telegram bot token (optional, press Enter to skip): "
            ).strip() or ""

        if telegram_token and not telegram_chat_id and self.mode == "interactive":
            telegram_chat_id = input("Enter your Telegram chat ID: ").strip()

        env_content = f"""# Hermes Portable Environment Configuration
# Generated by generate_config.py

# LLM Provider
HERMES_API_KEY={api_key}

# Telegram Bot (optional)
HERMES_TELEGRAM_TOKEN={telegram_token or ''}
HERMES_TELEGRAM_CHAT_ID={telegram_chat_id or ''}

# Hermes Paths
HERMES_HOME={self.output_dir}
HERMES_PORTABLE=true

# Logging
HERMES_LOG_LEVEL=INFO
NODE_ENV=production
"""
        return env_content

    def generate_config_yaml(self, api_key: Optional[str] = None) -> str:
        """Generate config.yaml content."""
        if not api_key:
            api_key = "sk-or-test-demo-key-no-api-configured"

        config_yaml = f"""# Hermes Portable Configuration
# Automatically generated - edit manually as needed

# Router (LLM Gateway)
router:
  base_url: "http://localhost:20128"  # 9router if available, fallback to OpenRouter
  api_key: "{api_key}"
  default_model: "openai/gpt-4o-mini"
  fallback_models:
    - "openai/gpt-4o"
    - "google/gemini-2.0-flash"

# MCP Servers (auto-discovered from embedded-mcps/)
mcp_servers:
  windows:
    name: "windows"
    enabled: true
    command: "python"
    args:
      - "-m"
      - "windows_mcp"
      - "serve"
    transport: "stdio"

# Gateway Platforms
gateway:
  platforms:
    telegram:
      enabled: false  # Enable if HERMES_TELEGRAM_TOKEN set
    discord:
      enabled: false
    slack:
      enabled: false

# Portable Mode
portable:
  enabled: true
  copy_runtime_to_localappdata: false

  tunnel:
    enabled: false
    dashboard_port: 8787

  wipe:
    failed_auth_threshold: 0

  remote:
    enabled: false
    max_fps: 10
    quality: 50
    idle_timeout: 600

# Agent Settings
agent:
  max_tool_iterations: 20
  tool_call_timeout_seconds: 60
  max_tool_calls_per_minute: 30

# Memory
memory:
  max_messages_per_chat: 20
  retention_messages: 1000

# Logging
logging:
  level: "INFO"
  stderr_format: "text"

# UX
ux:
  streaming_enabled: true
  typing_interval_seconds: 5
  progress_delay_seconds: 3
"""
        return config_yaml

    def write_files(
        self,
        api_key: Optional[str] = None,
        telegram_token: Optional[str] = None,
        telegram_chat_id: Optional[str] = None,
    ) -> bool:
        """Write config files to output directory."""
        try:
            # Ensure output directory exists
            self.output_dir.mkdir(parents=True, exist_ok=True)

            # Generate and write .env
            env_content = self.generate_env(
                api_key=api_key,
                telegram_token=telegram_token,
                telegram_chat_id=telegram_chat_id,
            )
            env_path = self.output_dir / ".env"
            env_path.write_text(env_content, encoding="utf-8")
            print(f"✅ Created {env_path}")

            # Generate and write config.yaml
            config_content = self.generate_config_yaml(api_key=api_key)
            config_path = self.output_dir / "config.yaml"
            config_path.write_text(config_content, encoding="utf-8")
            print(f"✅ Created {config_path}")

            return True

        except Exception as e:
            print(f"❌ Error writing config files: {e}", file=sys.stderr)
            return False


def main():
    """CLI entry point."""
    parser = argparse.ArgumentParser(
        description="Generate hermes-portable configuration files"
    )
    parser.add_argument(
        "--mode",
        choices=["auto", "interactive"],
        default="auto",
        help="Setup mode (default: auto for demo)",
    )
    parser.add_argument(
        "--output", type=Path, help="Output directory (default: ./data)"
    )
    parser.add_argument("--api-key", help="LLM API key (overrides prompt)")
    parser.add_argument("--telegram-token", help="Telegram bot token (overrides prompt)")
    parser.add_argument("--telegram-chat-id", help="Telegram chat ID (overrides prompt)")

    args = parser.parse_args()

    generator = ConfigGenerator(mode=args.mode, output_dir=args.output)

    print("🚀 Hermes Portable Config Generator")
    print("━" * 40)

    success = generator.write_files(
        api_key=args.api_key,
        telegram_token=args.telegram_token,
        telegram_chat_id=args.telegram_chat_id,
    )

    if success:
        print("\n✅ Configuration generated successfully!")
        print(f"📁 Output directory: {generator.output_dir}")
        return 0
    else:
        print("\n❌ Configuration generation failed", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
